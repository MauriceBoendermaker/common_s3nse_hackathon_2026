// zk/emit-program-vk.mjs
//
// One build step, two outputs — the second half.
//
// `build.mjs` already writes the browser artifacts and `zk/build/vk_data.rs`
// (which carries a sample proof for the standalone Rust test). This script
// writes the *program's* copy: `solana/programs/private_credit/src/vk.rs`,
// which contains the verifying key ONLY.
//
// Why a separate file rather than reusing vk_data.rs: the program must not
// carry a hard-coded proof. A judge grepping the deployed program's source for
// `PROOF_A` and finding one would be entirely right to ask what it is doing
// there. The program gets the key; nothing else.
//
// Regenerating the zkey changes the verifying key, so this file and
// `frontend/public/zk/` must always be regenerated together — otherwise every
// proof fails on-chain with a bare "proof invalid" and no clue why.

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { g1, g2 } from "./to_solana.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const buildDir = path.join(here, "build");
const outFile = path.join(
  here,
  "..",
  "solana",
  "programs",
  "private_credit",
  "src",
  "vk.rs",
);

const vkPath = path.join(buildDir, "verification_key.json");
if (!fs.existsSync(vkPath)) {
  console.error(
    `zk/emit-program-vk.mjs: ${vkPath} does not exist. Run \`npm run zk:build\` first.`,
  );
  process.exit(1);
}

const raw = fs.readFileSync(vkPath);
const vk = JSON.parse(raw.toString("utf8"));

if (vk.protocol !== "groth16") throw new Error(`vk.protocol is ${vk.protocol}, expected groth16`);
if (vk.curve !== "bn128") throw new Error(`vk.curve is ${vk.curve}, expected bn128`);

const nPublic = Number(vk.nPublic);
if (vk.IC.length !== nPublic + 1) {
  throw new Error(`vk.IC.length ${vk.IC.length} !== nPublic + 1 (${nPublic + 1})`);
}

// The hash the deployed program stores in its config account, so a running
// deployment can be matched to one circuit build without reading the ELF.
const vkHash = createHash("sha256").update(raw).digest();

const arr = (b) => "[" + [...b].join(",") + "]";
const ic = vk.IC.map((p, i) => g1(p, `vk.IC[${i}]`));

const source = `// GENERATED by zk/emit-program-vk.mjs — do not edit.
//
// The verifying key of zk/circuits/credit_policy.circom, in the byte layout
// groth16-solana 0.2.0 expects: 32-byte big-endian limbs, and G2 coordinates
// with c1 BEFORE c0.
//
// Two things about the crate this feeds, both verified rather than assumed:
//   * the published 0.2.0 struct field is misspelled \`vk_gamme_g2\`. Writing
//     \`vk_gamma_g2\` is a compile error. The published crate is not master.
//   * 0.2.0 is UNAUDITED. Only 0.0.1 was covered by the Light Protocol v3
//     audit. Widely used is not the same as audited.
//
// proof.A must be NEGATED by the client before submission — (x, p - y). That
// happens in backend/src/adapters/proofBytes.ts. Non-negated A is rejected
// on-chain, and it is the single most common reason a correct snarkjs proof
// fails here.

pub const NR_PUB: usize = ${nPublic};

/// SHA-256 over zk/build/verification_key.json, stored in the program config
/// at \`initialize\` so a deployment can be tied to one circuit build.
pub const VK_HASH: [u8; 32] = ${arr(vkHash)};

pub const VK_ALPHA_G1: [u8; 64]  = ${arr(g1(vk.vk_alpha_1, "vk.alpha"))};
pub const VK_BETA_G2:  [u8; 128] = ${arr(g2(vk.vk_beta_2, "vk.beta"))};
pub const VK_GAMMA_G2: [u8; 128] = ${arr(g2(vk.vk_gamma_2, "vk.gamma"))};
pub const VK_DELTA_G2: [u8; 128] = ${arr(g2(vk.vk_delta_2, "vk.delta"))};
pub const VK_IC: [[u8; 64]; ${ic.length}] = [
${ic.map((p) => "    " + arr(p)).join(",\n")}
];
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, source);

// The backend needs the same hash to prove the deployed config matches its own
// artifacts, and the frontend shows it. Emit it as JSON next to the build.
fs.writeFileSync(
  path.join(buildDir, "vk_hash.json"),
  JSON.stringify(
    {
      vkHashHex: "0x" + vkHash.toString("hex"),
      vkHashBytes: [...vkHash],
      nPublic,
      generatedAt: new Date().toISOString(),
    },
    null,
    2,
  ) + "\n",
);

console.log(`wrote ${outFile}`);
console.log(`  nPublic  = ${nPublic}`);
console.log(`  VK_IC    = ${ic.length} points`);
console.log(`  VK_HASH  = 0x${vkHash.toString("hex")}`);
